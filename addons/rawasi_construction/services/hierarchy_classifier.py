def classify(text):
    """يرجع dict بـ main_category / item_group / simplified_desc،
    أو dict كله None لو ما تطابقت أي قاعدة."""
    if not text:
        return {"main_category": None, "item_group": None,
                "simplified_desc": None}
    for keywords, levels in _HIERARCHY_RULES:
        for kw in keywords:
            if re.search(kw, text, re.IGNORECASE):
                mc, ig, sd = levels
                return {"main_category": mc, "item_group": ig,
                        "simplified_desc": sd}
    return {"main_category": None, "item_group": None,
            "simplified_desc": None}
