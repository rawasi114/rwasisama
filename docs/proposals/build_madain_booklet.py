def _rtl_p(p):
    pPr = p._p.get_or_add_pPr()
    b = OxmlElement('w:bidi'); b.set(qn('w:val'), '1'); pPr.append(b)
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT

def _run(r, size=11, bold=False, color=None, name=FONT):
    r.font.size = Pt(size); r.bold = bold; r.font.name = name
    if color is not None:
        r.font.color.rgb = color
    rp = r._element.get_or_add_rPr()
    rfo = rp.get_or_add_rFonts()
    rfo.set(qn('w:cs'), name); rfo.set(qn('w:ascii'), name); rfo.set(qn('w:hAnsi'), name)
    sz = OxmlElement('w:szCs'); sz.set(qn('w:val'), str(int(size*2))); rp.append(sz)
    rtl = OxmlElement('w:rtl'); rtl.set(qn('w:val'), '1'); rp.append(rtl)

def para(text="", size=11, bold=False, color=None, align=None, space_after=6, space_before=0):
    p = doc.add_paragraph(); _rtl_p(p)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.line_spacing = 1.25
    if text:
        r = p.add_run(text); _run(r, size, bold, color)
    return p

def bullet(text, size=11, bold=False, lvl=0):
    p = doc.add_paragraph(); _rtl_p(p)
    p.paragraph_format.left_indent = Cm(0.6 + 0.6*lvl)
    p.paragraph_format.right_indent = Cm(0.6 + 0.6*lvl)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.2
    r = p.add_run("•  " + text); _run(r, size, bold)
    return p

def section_title(text):
    p = doc.add_paragraph(); _rtl_p(p)
    p.paragraph_format.page_break_before = True
    p.paragraph_format.space_before = Pt(6); p.paragraph_format.space_after = Pt(8)
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement('w:shd'); shd.set(qn('w:val'),'clear'); shd.set(qn('w:fill'),'1F6E53'); pPr.append(shd)
    r = p.add_run(text); _run(r, 14, True, RGBColor(0xFF,0xFF,0xFF))
    return p

def clause(num, title):
    p = doc.add_paragraph(); _rtl_p(p)
    p.paragraph_format.space_before = Pt(8); p.paragraph_format.space_after = Pt(4)
    r = p.add_run(f"{num} - {title}"); _run(r, 12, True, GREEN)
    bar = p._p.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr'); bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'),'single'); bottom.set(qn('w:sz'),'6'); bottom.set(qn('w:space'),'2'); bottom.set(qn('w:color'),'1F6E53')
    pbdr.append(bottom); bar.append(pbdr)
    return p

def set_table_rtl(table):
    tblPr = table._tbl.tblPr
    bidi = OxmlElement('w:bidiVisual'); tblPr.append(bidi)

def shade_cell(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd'); shd.set(qn('w:val'),'clear'); shd.set(qn('w:fill'),fill); tcPr.append(shd)

def cell_text(cell, text, size=10, bold=False, color=None, align=WD_ALIGN_PARAGRAPH.RIGHT):
    cell.text = ""
    p = cell.paragraphs[0]; _rtl_p(p); p.alignment = align
    p.paragraph_format.space_after = Pt(1); p.paragraph_format.space_before = Pt(1)
    r = p.add_run(text); _run(r, size, bold, color)

def make_table(headers, rows, widths=None, header_fill='1F6E53', font=9):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_table_rtl(t)
    for i, h in enumerate(headers):
        cell_text(t.rows[0].cells[i], h, size=font, bold=True, color=RGBColor(0xFF,0xFF,0xFF), align=WD_ALIGN_PARAGRAPH.CENTER)
        shade_cell(t.rows[0].cells[i], header_fill)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cell_text(cells[i], str(val), size=font, align=WD_ALIGN_PARAGRAPH.CENTER if i!=len(headers)-1 else WD_ALIGN_PARAGRAPH.RIGHT)
    if widths:
        for i,w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    return t

