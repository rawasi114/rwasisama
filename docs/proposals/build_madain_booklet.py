clause(10, "المساواة والشفافية")
para("على الجهة الحكومية إطلاع كافة المتنافسين على المعلومات ذات العلاقة بنطاق العمل في المنافسة بما يمكّنهم من تقييم الأعمال قبل الحصول على وثائق المنافسة، وتلتزم بمبدأ تكافؤ الفرص والمساواة بين جميع المتنافسين وعدم التمييز بينهم، وتوفير المعلومات ذاتها لجميع الراغبين في المشاركة في الوقت ذاته دون تفضيل أحدهم على الآخر.")

clause(11, "تعارض المصالح")
para("يلتزم المتنافس – ومتعاقدوه من الباطن العاملون ضمن نطاق هذه المنافسة – بإبلاغ الجهة الحكومية والإفصاح كتابةً عن أي حالة تعارض في المصالح أو أي مصلحة خاصة نشأت أو ستنشأ أو قد تنشأ عن أي تعامل يكون من شأنه التأثير في حياد المتنافس أو نزاهة المنافسة، وللجهة الحكومية استبعاد العرض الذي يثبت وجود تعارض مصالح مؤثّر بشأنه.")

clause(12, "السلوكيات والأخلاقيات")
para("يلتزم المتنافس بأعلى معايير السلوك المهني والأمانة والنزاهة أثناء المنافسة وتنفيذ العقد، ويُحظر عليه القيام بأي ممارسة احتيالية أو تواطؤ أو تقديم وعد أو هدية أو عمولة أو أي منفعة لأي موظف بقصد التأثير على إجراءات المنافسة، وللجهة اتخاذ ما يلزم نظاماً حيال مخالفة ذلك.")

clause(13, "السرية وإفشاء المعلومات")
para("يلتزم المتنافس بالمحافظة على سرية المعلومات والوثائق التي يطّلع عليها بسبب مشاركته في المنافسة أو تنفيذه للعقد، وعدم إفشائها أو استخدامها في غير الغرض المخصّص لها، ويستمر هذا الالتزام سارياً بعد انتهاء المنافسة أو العقد.")

clause(14, "ملكية وثائق المنافسة")
para("تظلّ جميع وثائق المنافسة والمخطّطات والبيانات ملكاً للجهة الحكومية، ولا يجوز للمتنافس استخدامها لغير أغراض إعداد عرضه، وعليه إعادتها أو إتلافها عند طلب الجهة ذلك.")

clause(15, "حقوق الملكية الفكرية")
para("يضمن المتنافس أن تنفيذ الأعمال والمواد والبرمجيات والتصاميم المقدّمة لا تنتهك أي حقوق ملكية فكرية للغير، ويتحمّل وحده كامل المسؤولية النظامية والمالية المترتّبة على أي مطالبة من هذا القبيل.")

clause(16, "المحتوى المحلي")
para("يلتزم المتعاقد ومتعاقدوه من الباطن بإعطاء الأفضلية للمنتجات والخدمات الوطنية، وبتطبيق آلية الوزن النسبي لتفضيل المحتوى المحلي والمنشآت الصغيرة والمتوسطة وفقاً للأنظمة والتعاميم الصادرة عن هيئة المحتوى المحلي والمشتريات الحكومية، والالتزام بالقائمة الإلزامية حال انطباقها على نطاق العمل.")

clause(17, "أنظمة وأحكام الاستيراد")
para("في حال اشتمال نطاق العمل على مواد أو أصناف مستوردة، يلتزم المتعاقد بكافة أنظمة وأحكام الاستيراد المعمول بها في المملكة، وباستيفاء شهادات المنشأ والمطابقة (saber) والإفراج الجمركي على نفقته ومسؤوليته.")

clause(18, "تجزئة المنافسة")
para("[ تُحدّد الجهة قابلية المنافسة للتجزئة من عدمها ] — هذه المنافسة غير قابلة للتجزئة، ويتعيّن على المتنافس تقديم عرضه شاملاً كامل نطاق العمل، ولا يُقبل العرض الجزئي ما لم تنص الجهة على خلاف ذلك.")

clause(19, "الاستبعاد من المنافسة")
para("يُستبعد العرض في أيٍّ من الحالات المنصوص عليها نظاماً، ومنها: عدم استيفاء شروط التأهيل أو الوثائق المطلوبة، أو وجود تعارض مصالح مؤثّر، أو ثبوت تقديم معلومات أو مستندات غير صحيحة، أو التحفّظ على الشروط أو جداول الكميات، أو عدم الالتزام بالقائمة الإلزامية للمحتوى المحلي، أو إذا كان العرض مخالفاً للشروط والمواصفات بما يحول دون الترسية عليه.")

clause(20, "إلغاء المنافسة وأثره")
para("للجهة الحكومية إلغاء المنافسة قبل الترسية في الحالات التي يجيزها النظام، ولا يترتّب على الإلغاء أي حقٍّ للمتنافسين في التعويض، وتُعاد قيمة وثائق المنافسة في حال الإلغاء لأسباب تعود للجهة وفقاً لما تقضي به اللائحة.")

clause(21, "التفاوض مع أصحاب العروض")
para("للجهة الحكومية – في الحالات التي يجيزها النظام واللائحة – التفاوض مع أصحاب العروض على النحو الذي يحقّق مصلحتها، وبما يكفل مبدأ المساواة والشفافية بين المتنافسين.")

clause(22, "التضامن")
para("في حال تقديم العرض من ائتلاف، يكون جميع أعضاء الائتلاف مسؤولين بالتضامن والتكافل أمام الجهة الحكومية عن تنفيذ كامل التزامات العقد، ويُقدَّم اتفاق الائتلاف موثّقاً ومحدّداً فيه العضو الممثّل والممسك للحساب ونِسب المشاركة.")

clause(23, "التعاقد من الباطن")
para("لا يجوز للمتعاقد التنازل عن العقد أو التعاقد من الباطن على كامل الأعمال، ويجوز له – بموافقة الجهة الكتابية المسبقة – التعاقد من الباطن على جزء منها، ويبقى المتعاقد الرئيس مسؤولاً أمام الجهة الحكومية عن الأعمال المتعاقد على تنفيذها بعقود الباطن وفقاً للشروط والمواصفات.")

clause(24, "التأهيل اللاحق")
para("للجهة الحكومية التحقّق من قدرة المتنافس صاحب العرض المرشّح للترسية على تنفيذ العقد (التأهيل اللاحق) وفقاً للمعايير والأوزان الموضّحة في ملحق معايير التأهيل اللاحق، وذلك قبل إصدار قرار الترسية.")

clause(25, "إلزامية العرض")
para("يُعدّ تقديم العرض إقراراً من المتنافس باطّلاعه على كامل وثائق المنافسة وفهمه لها وقبوله بها، ويكون عرضه ملزِماً له طوال مدة صلاحيته، ولا يحقّ له الرجوع عنه أو تعديله بعد الموعد المحدّد لتقديم العروض.")

